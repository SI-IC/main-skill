test("safeReadFile: файл свыше капа читается как пустой (диф → fail toward deny)", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "cg-cap-"));
  const fp = path.join(dir, "big.js");
  fs.writeFileSync(fp, "// старый\n" + "x".repeat(300_000));
  assert.equal(g.safeReadFile(fp), "");
  const out = g.evaluate(
    {
      tool_name: "Write",
      tool_input: { file_path: fp, content: "// старый\nx" },
    },
    { env: {}, readFile: g.safeReadFile },
  );
  assert.equal(out.decision, "deny");
  fs.rmSync(dir, { recursive: true, force: true });
});
