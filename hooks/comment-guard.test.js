const test = require("node:test");
const assert = require("node:assert");
const fs = require("fs");
const os = require("os");
const path = require("path");
const g = require("./comment-guard");

const editPayload = (fp, newS, oldS = "") => ({
  tool_name: "Edit",
  tool_input: { file_path: fp, old_string: oldS, new_string: newS },
});
const writePayload = (fp, content) => ({
  tool_name: "Write",
  tool_input: { file_path: fp, content },
});
const noRead = () => "";

test("commentBody: снимает обрамление всех семейств", () => {
  assert.equal(g.commentBody("// привет"), "привет");
  assert.equal(g.commentBody("# привет"), "привет");
  assert.equal(g.commentBody("-- привет"), "привет");
  assert.equal(g.commentBody("/* привет */"), "привет");
  assert.equal(g.commentBody("/** привет */"), "привет");
});

test("commentBody: многострочный блок схлопывается в одну строку", () => {
  assert.equal(g.commentBody("/*\n * первая\n * вторая\n */"), "первая вторая");
});

test("commentBody: пустой комментарий-разделитель → пусто", () => {
  assert.equal(g.commentBody("//"), "");
  assert.equal(g.commentBody("// ───────────"), "───────────");
});

test("isSanctionedComment: канонический русский префикс", () => {
  assert.ok(g.isSanctionedComment("Не менять, потому что statSync виснет"));
  assert.ok(g.isSanctionedComment("не менять потому что порядок значим"));
  assert.ok(g.isSanctionedComment("Не менять — потому что кап в байтах"));
});

test("isSanctionedComment: английский эквивалент для нерусских проектов", () => {
  assert.ok(g.isSanctionedComment("Do not change because order matters"));
  assert.ok(g.isSanctionedComment("Don't change, because the cap is in bytes"));
});

test("isSanctionedComment: префикс без содержания и близкие формы — нет", () => {
  assert.ok(!g.isSanctionedComment("Не менять"));
  assert.ok(!g.isSanctionedComment("Не менять, потому что"));
  assert.ok(!g.isSanctionedComment("не трогать, потому что сломается"));
  assert.ok(!g.isSanctionedComment("тут потому что важно"));
});

