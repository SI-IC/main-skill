test("commentBody: прогон звёзд без закрывающего слэша не даёт backtracking", () => {
  const t0 = Date.now();
  g.commentBody("/*a" + "*".repeat(80000));
  const dt = Date.now() - t0;
  assert.ok(dt < 500, `commentBody квадратичен: ${dt}ms`);
  assert.equal(g.commentBody("/* x **/"), "x");
  assert.equal(g.commentBody("/* x */"), "x");
});

